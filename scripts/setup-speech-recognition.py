def digest(path):
    sha = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            sha.update(chunk)
    return sha.hexdigest()


def target(root, name):
    path = Path(name)
    if path.is_absolute() or ".." in path.parts:
        raise ValueError(f"Unsafe asset path: {name}")
    result = root
    for part in ("", *path.parts):
        result = result / part
        if result.is_symlink():
            raise ValueError(f"Refusing a symlink asset path: {result}")
    return result


def valid(root, name):
    path = target(root, name)
    return path.is_file() and digest(path) == EXPECTED[name]


def download(url, destination, sha=None):
    print(f"Downloading {url}", flush=True)
    subprocess.run([
        "curl", "--fail", "--location", "--show-error", "--silent", "--retry", "3",
        "--connect-timeout", "20", "--max-time", "600", "--output", str(destination), url,
    ], check=True)
    if sha and digest(destination) != sha:
        raise ValueError(f"SHA-256 mismatch for {url}; downloaded file will not be installed")


def asset_names(platform):
    return [name for name in EXPECTED
            if (platform != "ios" or not name.startswith("android/"))
            and (platform != "android" or not name.startswith("frameworks/"))]


def prepare(platform="all"):
    missing = [name for name in asset_names(platform) if not valid(VENDOR, name)]
    if missing:
        VENDOR.parent.mkdir(parents=True, exist_ok=True)
        with tempfile.TemporaryDirectory(prefix=".speech-assets-", dir=VENDOR.parent) as work:
            work = Path(work)
            stage = work / "stage"
            stage.mkdir()
            if "android/sherpa-onnx.aar" in missing:
                aar = target(stage, "android/sherpa-onnx.aar")
                aar.parent.mkdir(parents=True)
                download(ANDROID_URL, aar, ANDROID_SHA)
            if any(name.startswith("frameworks/") for name in missing):
                archive = work / "framework.zip"
                download(FRAMEWORK_URL, archive, FRAMEWORK_SHA)
                with zipfile.ZipFile(archive) as package:
                    for member in package.infolist():
                        if member.is_dir():
                            continue
                        name = f"frameworks/{member.filename}"
                        path = target(stage, name)
                        if name not in EXPECTED or stat.S_ISLNK(member.external_attr >> 16):
                            raise ValueError(f"Unexpected framework member: {member.filename}")
                        path.parent.mkdir(parents=True, exist_ok=True)
                        with package.open(member) as source, path.open("wb") as output:
                            shutil.copyfileobj(source, output)
                        path.chmod((member.external_attr >> 16) & 0o777)
            if any(name.startswith("model/") for name in missing):
                archive = work / "model.tar.bz2"
                download(MODEL_URL, archive, MODEL_SHA)
                model_files = {f"{MODEL}/{Path(name).name}": name for name in EXPECTED if name.startswith("model/")}
                with tarfile.open(archive, "r|bz2") as package:
                    for member in package:
                        if member.name not in model_files:
                            continue
                        if not member.isfile():
                            raise ValueError(f"Model member is not a regular file: {member.name}")
                        path = target(stage, model_files[member.name])
                        path.parent.mkdir(parents=True, exist_ok=True)
                        with package.extractfile(member) as source, path.open("wb") as output:
                            shutil.copyfileobj(source, output)
            for name, url in LICENSE_URLS.items():
                if name in missing:
                    response = work / "license.json"
                    download(url, response)
                    path = target(stage, name)
                    path.parent.mkdir(parents=True, exist_ok=True)
                    path.write_bytes(base64.b64decode(json.loads(response.read_text())["content"]))
            # Verify everything before replacing any installed file; interrupted runs are repairable.
            for name in missing:
                if not valid(stage, name):
                    raise ValueError(f"Missing or corrupt extracted asset: {name}")
            for name in missing:
                path = target(VENDOR, name)
                path.parent.mkdir(parents=True, exist_ok=True)
                os.replace(target(stage, name), path)
    VENDOR.mkdir(parents=True, exist_ok=True)
    target(VENDOR, "SOURCES.md").write_text(SOURCES)
    print("Offline speech assets ready (sherpa-onnx 1.13.8 + Chinese Zipformer).")


def self_test():
    with tempfile.TemporaryDirectory() as directory:
        root = Path(directory)
        file = root / "file"
        file.write_bytes(b"abc")
        assert digest(file) == "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        (root / "link").symlink_to(file)
        for name in ("../escape", "/absolute", "link"):
            try:
                target(root, name)
            except ValueError:
                pass
            else:
                raise AssertionError(f"Unsafe path accepted: {name}")
    print("Speech asset checksum and path safety checks passed.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify prepared assets without network access")
    parser.add_argument("--self-test", action="store_true", help="Run the small checksum/path safety check")
    parser.add_argument("--platform", choices=("ios", "android", "all"), default="all", help="Prepare one platform or both (default)")
    args = parser.parse_args()
    try:
        if args.self_test:
            self_test()
        elif args.check:
            names = asset_names(args.platform)
            missing = [name for name in names if not valid(VENDOR, name)]
            if missing:
                raise ValueError("Run pnpm setup:speech; missing/corrupt assets: " + ", ".join(missing))
            print(f"Verified all {len(names)} {args.platform} offline speech assets.")
        else:
            prepare(args.platform)
    except (OSError, ValueError, KeyError, subprocess.CalledProcessError, tarfile.TarError, zipfile.BadZipFile) as error:
        print(f"Speech asset preparation failed: {error}", file=sys.stderr)
        sys.exit(1)
